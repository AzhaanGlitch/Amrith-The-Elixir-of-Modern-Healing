// Utility to get the user-friendly label for any snake_case symptom id
export const getSymptomLabel = (symptomId) => {
  for (const category of symptomCategories) {
    const found = category.symptoms.find(s => s.id === symptomId);
    if (found) return found.label;
  }
  
  // Fallback formatter
  return symptomId
    .replace(/_/g, ' ')
    .replace(/\b\w/g, c => c.toUpperCase())
    .replace(/\bGm\b/i, 'General Medicine')
    .replace('(typhos)', '(Typhus)');
};

// Complete list of all 131 symptoms for validation / quick searches
export const allSymptomsList = symptomCategories.reduce((acc, cat) => {
  return [...acc, ...cat.symptoms];
}, []);
